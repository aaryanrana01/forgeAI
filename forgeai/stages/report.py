"""Requirement 7 - Honest reporting: scorecards, iteration log and REPORT.md
that says what still fails and why."""

from __future__ import annotations

from ..schemas import CaseResult, Scorecard


def pct(x: float) -> str:
    return f"{x * 100:.0f}%"


def scorecard_table(cards: list[Scorecard]) -> str:
    cats = sorted({c for s in cards for c in s.by_category})
    head = "| Iteration | Def. version | Overall | 95% CI | Dev | Holdout | " + " | ".join(cats) + \
           " | Retrieval hit | Fact recall | Grounded | Refusal recall | Over-refusal |"
    sep = "|" + "---|" * (head.count("|") - 1)
    rows = [head, sep]
    for s in cards:
        cat_cells = " | ".join(
            f"{s.by_category[c]['passed']}/{s.by_category[c]['n']}" if c in s.by_category else "-" for c in cats)
        m = s.metrics
        rows.append(f"| {s.label} | v{s.definition_version} | **{pct(s.pass_rate)}** ({s.passed}/{s.n_cases}) | "
                    f"{pct(s.ci95[0])}-{pct(s.ci95[1])} | {pct(s.dev_pass_rate)} | {pct(s.holdout_pass_rate)} | "
                    f"{cat_cells} | {pct(m['retrieval_hit_rate'])} | {pct(m['mean_fact_recall'])} | "
                    f"{pct(m['grounded_rate'])} | {pct(m['refusal_recall'])} | {pct(m['over_refusal_rate'])} |")
    return "\n".join(rows)


def iteration_log_markdown(log: list[dict]) -> str:
    md = ["# Critic-optimizer iteration log", ""]
    for it in log:
        md.append(f"## Iteration {it['iteration']} - {it['decision']}")
        md.append(f"Dev pass-rate {pct(it['score_before']['dev'])} -> {pct(it['score_after']['dev'])}; "
                  f"holdout {pct(it['score_before']['holdout'])} -> {pct(it['score_after']['holdout'])}; "
                  f"overall {pct(it['score_before']['overall'])} -> {pct(it['score_after']['overall'])}. "
                  f"Tokens spent: {it.get('tokens', 0):,}.")
        md.append("")
        md.append(f"Dev failures going in: {it.get('failures_in', {})}")
        for p in it["patches"]:
            md.append(f"- **{p['id']} [{p['category']}] {p['target']}** - {p['rationale']}  ")
            md.append(f"  addresses: {', '.join(p['addressed_cases'])}  ")
            md.append(f"  before: `{_short(p['before'])}`  ")
            md.append(f"  after: `{_short(p['after'])}`")
        if it.get("fixed"):
            md.append(f"- now passing: {', '.join(it['fixed'])}")
        if it.get("broken"):
            md.append(f"- newly failing: {', '.join(it['broken'])}")
        if it.get("note"):
            md.append(f"- note: {it['note']}")
        md.append("")
    return "\n".join(md)


def _short(v, n: int = 260) -> str:
    s = str(v).replace("`", "'").replace("\n", " ")
    return s if len(s) <= n else s[:n] + " ..."


EXPLAIN = {
    "retrieval_miss": "the search step never put the needed passage in front of the model",
    "hallucination": "the answer stated something the evidence does not contain",
    "wrong_refusal": "the agent refused when it should answer, or answered when it should refuse",
    "prompt_defect": "the facts were available but the agent's instructions led to an incomplete or malformed reply",
}


def build_report(*, req, gr, tool_audit, tournament, cards: list[Scorecard], log: list[dict],
                 final_results: list[CaseResult], final_def, calibration: dict, meter: dict, settings: dict,
                 eval_meta: dict, stop_reason: str, best_label: str, fake_backend: bool) -> str:
    final = cards[-1] if cards else None
    best = next((c for c in cards if c.label == best_label), final)
    md = []
    if fake_backend:
        md += ["> **WARNING - PLUMBING TEST RUN.** This run used the scripted fake model from the test-suite. "
               "Scores below say nothing about agent quality.", ""]
    md += [f"# ForgeAI report - {req.agent_name}", ""]
    if best:
        lo, hi = best.ci95
        md += [f"**Shipped definition v{best.definition_version}: {pct(best.pass_rate)} of {best.n_cases} generated "
               f"cases pass** (95% CI {pct(lo)}-{pct(hi)}; dev {pct(best.dev_pass_rate)}, untouched holdout "
               f"{pct(best.holdout_pass_rate)}).", ""]
        gap = best.dev_pass_rate - best.holdout_pass_rate
        if gap > 0.15:
            md += [f"⚠ Dev beats holdout by {gap * 100:.0f} points: the optimizer may have fitted the dev cases. "
                   "Trust the holdout number more.", ""]
        if best.pass_rate >= 0.999:
            md += ["⚠ 100% is suspicious: the eval set was generated by the same pipeline. Read the limitations "
                   "section before trusting it.", ""]
    md += ["Factory model `{}`; judge model `{}`; embeddings `{}`. Stop reason: {}.".format(
        settings.get("model"), settings.get("judge_model"), settings.get("embed_model") or "none (BM25 only)",
        stop_reason), ""]

    md += ["## 1. Requirements and groundability", "", f"Scope: {req.scope}", "",
           f"Groundability: {gr.summary}", ""]
    if gr.flagged_gaps:
        md += ["Flagged gaps (requested in the brief, NOT supported by the documents, so the agent refuses them):"]
        md += [f"- {g}" for g in gr.flagged_gaps] + [""]

    md += ["## 2. Tool selection", "", "| Tool | Attached | Why |", "|---|---|---|"]
    for t in tool_audit:
        md.append(f"| {t['tool']} | {'yes' if t['final'] else 'no'} | {t['why']} |")
    md.append("")

    if tournament:
        md += ["## 3. Prompt tournament", "", f"{len(tournament['candidates'])} candidate system prompts were scored on "
               f"{tournament['n_cases']} dev cases (absolute pass rates, no pairwise LLM preference).", "",
               "| Candidate | Dev pass | Fact recall | Prompt words |", "|---|---|---|---|"]
        for c in tournament["candidates"]:
            md.append(f"| {c['style']}{' **(winner)**' if c['style'] == tournament['winner'] else ''} | "
                      f"{c['passed']}/{c['n']} | {pct(c['fact_recall'])} | {c['prompt_words']} |")
        md += ["", tournament.get("note", ""), ""]

    md += ["## 4. Scorecard per iteration", "", scorecard_table(cards), ""]
    md += ["## 5. What changed", ""]
    if not log:
        md += ["No optimizer iterations ran.", ""]
    for it in log:
        md.append(f"- **Iteration {it['iteration']}** ({it['decision']}): " + "; ".join(
            f"{p['id']} {p['category']} -> {p['target']} ({p['rationale'][:160]})" for p in it["patches"])
                  + f". Dev {pct(it['score_before']['dev'])} -> {pct(it['score_after']['dev'])}."
                  + (f" Fixed {len(it['fixed'])}, broke {len(it['broken'])}." if 'fixed' in it else ""))
    md.append("")

    fails = [r for r in final_results if not r.passed]
    md += [f"## 6. What still fails and why ({len(fails)} of {len(final_results)})", ""]
    by: dict[str, list[CaseResult]] = {}
    for r in fails:
        by.setdefault(r.failure_category or "unclassified", []).append(r)
    for cat, rs in sorted(by.items(), key=lambda kv: -len(kv[1])):
        md += [f"### {cat} - {len(rs)} case(s)", f"_{EXPLAIN.get(cat, '')}_", ""]
        for r in rs:
            md.append(f"- `{r.case_id}` ({r.category}, {r.split}) \"{r.question[:140]}\" -> {r.failure_subtype}: "
                      f"{r.failure_reason[:220]}")
        md.append("")
    if not fails:
        md += ["Nothing in the generated set fails. That says as much about the eval set's reach as about the "
               "agent - see limitations.", ""]

    md += ["## 7. How far to trust the judge", "",
           f"Calibration probe (known-good, padded-with-fabrication and wrong-number answers): LLM judge accuracy "
           f"{pct(calibration.get('llm_judge_accuracy', 0))}, combined with deterministic checks "
           f"{pct(calibration.get('combined_accuracy', 0))}. LLM grounding vote "
           f"{'ENABLED' if calibration.get('llm_grounding_vote_enabled') else 'DISABLED (failed calibration) - only code checks decide grounding'}.",
           "", "Defences in use: per-fact yes/no grading against document-extracted facts; numbers checked by code "
           "(the LLM can never accept a different number); claim-support *ratio* so padding cannot raise a score; "
           "evidence shown in two orders when a verdict is negative; no pairwise comparisons anywhere."
           + (" Judge and factory are the SAME model family - self-preference risk remains; set FORGE_JUDGE_MODEL "
              "to a different family to reduce it." if calibration.get("same_model_family") else
              " Judge and factory are different model families."), ""]
    if calibration.get("order_checks"):
        md += [f"Order-swap re-checks: {calibration['order_checks']}, verdict flips: "
               f"{calibration.get('order_disagreements', 0)}.", ""]

    md += ["## 8. Limitations of this evaluation", "",
           f"- {eval_meta.get('n_cases')} cases is a small sample: the 95% interval above is wide on purpose.",
           "- Cases were generated by the factory model from sampled passages: topics in unsampled passages are untested.",
           "- Paraphrase edge cases share facts with their parent case, so they are not independent evidence.",
           f"- {eval_meta.get('n_dropped', 0)} generated candidates were rejected by verification "
           "(see 04_evals/dropped_cases.json) - evidence that the generator is imperfect.",
           "- Dates in tool cases are resolved against the day the eval runs.", ""]
    md += ["## 9. Cost", "", f"{meter.get('llm_calls')} model calls ({meter.get('cached_calls')} served from cache), "
           f"{meter.get('total_tokens', 0):,} tokens, {meter.get('elapsed_seconds')} s wall-clock. "
           f"Per stage: see run_meta.json.", ""]
    md += ["## 10. Run the agent", "", "```bash", "python -m forgeai chat <this-run-folder>/agent_definition.json",
           "```", ""]
    return "\n".join(md)
